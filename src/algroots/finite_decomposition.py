"""Radicals and primary factors over characteristic-zero and finite coefficient fields."""

import sympy as sp
from sympy.polys.matrices import DomainMatrix

from .domains import polynomial, polynomial_domain
from .finite_fields import factor_univariate, field_order, is_finite_field
from .quotient import QuotientAlgebra


def _generators(algebra):
    return tuple(p.as_expr() for p in algebra.groebner_basis.polys)


def nilradical_basis(algebra):
    """Return a coefficient-field basis of the nilradical of a finite algebra.

    In characteristic zero the kernel of (a,b) -> Tr(ab) is exactly the
    nilradical, including for products of finite separable residue fields.
    Over a finite field GF(q), a sufficiently high q-power Frobenius kernel
    replaces the trace kernel. The returned expressions use the algebra's
    standard monomial coordinates.
    """
    if not isinstance(algebra, QuotientAlgebra):
        raise TypeError("a QuotientAlgebra is required")
    if not algebra.dimension:
        return ()
    if algebra.domain.characteristic():
        if not is_finite_field(algebra.domain):
            raise NotImplementedError(
                "Frobenius nilradicals require a finite perfect coefficient field"
            )
        power = 1
        exponent = 0
        q = field_order(algebra.domain)
        while power < algebra.dimension:
            power *= q
            exponent += 1
        operator = frobenius_matrix(algebra).pow(exponent)
    else:
        operator = algebra._trace_domain_pairing.convert_to(polynomial_domain(algebra.domain))
    kernel = operator.nullspace(divide_last=True)
    rows = kernel.to_dod()
    return tuple(
        algebra.normal_form(
            sum(
                algebra.domain.to_sympy(c) * algebra.standard_monomials[j]
                for j, c in rows.get(i, {}).items()
            )
        )
        for i in range(kernel.shape[0])
    )


def reduced_algebra(algebra, *, groebner_backend="native", groebner_limits=None):
    """Return A divided by its nilradical using verified native or explicit SymPy construction."""
    nilpotents = nilradical_basis(algebra)
    generators = (*_generators(algebra), *nilpotents)
    return QuotientAlgebra.from_polynomials(
        generators,
        algebra.variables,
        domain=algebra.domain,
        order=str(algebra.groebner_basis.order),
        groebner_backend=groebner_backend,
        groebner_limits=groebner_limits,
    )


def primary_decomposition(
    algebra, *, max_separating_attempts=64, groebner_backend="native", groebner_limits=None
):
    """Return pairs (primary factor algebra, residue field) for a finite algebra.

    A separating linear form distinguishes all geometric points. If its
    characteristic polynomial contains p(t)^e, adjoining p(l)^e selects the
    associated local algebra by the Chinese remainder theorem. Adjoining p(l)
    to the reduced algebra gives its residue field. Nilpotent directions are
    retained even when the local algebra is not generated by one element.
    Component bases default to native F4; ``groebner_backend="sympy"`` keeps
    construction portable. ``groebner_limits`` applies to each new basis.
    Finite fields instead split through the Frobenius-fixed subalgebra, which
    also handles products having more factors than the base field has elements.
    """
    if not isinstance(algebra, QuotientAlgebra):
        raise TypeError("a QuotientAlgebra is required")
    if (
        isinstance(max_separating_attempts, bool)
        or not isinstance(max_separating_attempts, (int, sp.Integer))
        or max_separating_attempts < 1
    ):
        raise ValueError("max_separating_attempts must be a positive integer")
    if not algebra.dimension:
        return ()
    if algebra.domain.characteristic():
        return _finite_primary(algebra, groebner_backend, groebner_limits)
    parameter = sp.Dummy("component_parameter")
    separator = algebra.separating_element(parameter, max_attempts=int(max_separating_attempts))
    characteristic = algebra.characteristic_polynomial(separator.expression, parameter)
    reduced = reduced_algebra(
        algebra, groebner_backend=groebner_backend, groebner_limits=groebner_limits
    )
    result = []
    factors = (
        algebra.domain.factor_univariate(characteristic)[1]
        if getattr(algebra.domain, "is_AlgebraicFunctionField", False)
        else characteristic.factor_list()[1]
    )
    for factor, exponent in factors:
        value = factor.as_expr().subs(parameter, separator.expression)
        component = QuotientAlgebra.from_polynomials(
            (*_generators(algebra), value**exponent),
            algebra.variables,
            domain=algebra.domain,
            groebner_backend=groebner_backend,
            groebner_limits=groebner_limits,
        )
        residue = QuotientAlgebra.from_polynomials(
            (*_generators(reduced), value),
            algebra.variables,
            domain=algebra.domain,
            groebner_backend=groebner_backend,
            groebner_limits=groebner_limits,
        )
        result.append((component, residue))
    return tuple(result)


__all__ = ["nilradical_basis", "reduced_algebra", "primary_decomposition", "frobenius_matrix"]


def _power(algebra, value, exponent):
    result = sp.S.One
    while exponent:
        if exponent % 2:
            result = algebra.normal_form(result * value)
        exponent //= 2
        if exponent:
            value = algebra.normal_form(value * value)
    return result


def frobenius_matrix(algebra):
    """Return the q-power Frobenius matrix over a finite coefficient field GF(q).

    The q-power map fixes coefficients and is linear. Its sufficiently high
    powers kill exactly the nilradical. Prime-characteristic trace kernels do
    not have that property when local lengths are divisible by p.
    """
    q = field_order(algebra.domain)
    entries = {}
    for column, monomial in enumerate(algebra.standard_monomials):
        value = polynomial(_power(algebra, monomial, q), algebra.variables, algebra.domain)
        for exponent, coefficient in value.rep.to_dict().items():
            entries.setdefault(algebra._basis_index[exponent], {})[column] = coefficient
    return DomainMatrix(entries, (algebra.dimension, algebra.dimension), algebra.domain)


def _finite_primary(algebra, backend, limits):
    """Split through Frobenius-fixed elements, including nonmonogenic products."""
    if not is_finite_field(algebra.domain):
        raise NotImplementedError(
            "positive-characteristic primary factors require finite constants"
        )
    reduced = reduced_algebra(algebra, groebner_backend=backend, groebner_limits=limits)
    fixed = (
        frobenius_matrix(reduced)
        - DomainMatrix.eye((reduced.dimension, reduced.dimension), algebra.domain)
    ).nullspace(divide_last=True)
    splitter = None
    for row in fixed.to_dod().values():
        if any(c for j, c in row.items() if j):
            splitter = sum(
                algebra.domain.to_sympy(c) * reduced.standard_monomials[j] for j, c in row.items()
            )
            break
    if splitter is None:
        return ((algebra, reduced),)
    parameter = sp.Dummy("fixed_value")
    characteristic = reduced.characteristic_polynomial(splitter, parameter)
    power = 1
    q = field_order(algebra.domain)
    while power < algebra.dimension:
        power *= q
    result = []
    for factor, _ in factor_univariate(characteristic)[1]:
        if factor.degree() != 1:
            raise ArithmeticError("a Frobenius-fixed element has a non-linear factor")
        root = -factor.nth(0) / factor.nth(1)
        equation = _power(algebra, splitter - root, power)
        component = QuotientAlgebra.from_polynomials(
            (*_generators(algebra), equation),
            algebra.variables,
            domain=algebra.domain,
            groebner_backend=backend,
            groebner_limits=limits,
        )
        if component.dimension:
            result.extend(_finite_primary(component, backend, limits))
    return tuple(result)
